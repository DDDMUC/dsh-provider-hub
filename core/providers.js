/** The credential reference for a custom (preset-less) route. */
export function customEnvName(route) {
  const slug = String(route ?? '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
  return `${slug || 'CUSTOM'}_API_KEY`
}
